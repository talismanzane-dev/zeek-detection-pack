"""Sigma serialization (Sigma 2.x rules and correlation rules, YAML)."""

from __future__ import annotations

from typing import Any

import yaml

from zdp import __version__
from zdp.rules import SigmaRule


class _Dumper(yaml.SafeDumper):
    """Block-style YAML with readable multi-line strings and no anchors/aliases."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _str_representer(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_representer)


def dump_document(doc: dict[str, Any]) -> str:
    return yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def render_sigma_file(rule: SigmaRule, config_hash: str) -> str:
    header = [
        "# Generated by `zdp export --format sigma` — do not edit; re-export instead.",
        f"# zdp {__version__} | detector: {rule.detector} | signal: {rule.signal} | "
        f"config: {config_hash}",
        f"# zdp-tier: {rule.tier}",
    ]
    header += [f"# note: {n}" for n in rule.notes]
    docs = [dump_document(d) for d in (*rule.companions, rule.document)]
    return "\n".join(header) + "\n" + "---\n".join(docs)
